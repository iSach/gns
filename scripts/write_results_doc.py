#!/usr/bin/env python
"""Turn the evaluated runs into docs/RESULTS.md.

    python scripts/write_results_doc.py --results <runs> --out docs/RESULTS.md

The table is generated, never hand-edited, so the numbers in the document always
match the result files they came from.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from gns import paper


def ratio(ours: float, published: float) -> str:
    return f"{ours / published:.1f}x" if published else "-"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", required=True, type=Path)
    parser.add_argument("--out", type=Path, default=Path("docs/RESULTS.md"))
    parser.add_argument("--pattern", default="**/result_test_best.json")
    parser.add_argument(
        "--ablation-pattern", default="**/result_test_latest.json"
    )
    args = parser.parse_args()

    def load(pattern):
        return [
            json.loads(path.read_text())
            for path in sorted(args.results.glob(pattern))
        ]

    # Table 1 quotes the validation-selected checkpoint, as the paper does; the
    # ablations quote the final one so every configuration is at 400k steps.
    headline = [
        r
        for r in load(args.pattern)
        if r["dataset"] in paper.TABLE_1 and "ablation_axis" not in r
    ]
    headline.sort(key=lambda r: r["dataset"])
    ablations = [r for r in load(args.ablation_pattern) if "ablation_axis" in r]

    lines = [
        "# Results",
        "",
        "Generated by `scripts/write_results_doc.py`; do not edit by hand.",
        "",
        "## Table 1",
        "",
        "One-step and rollout mean squared error on the full test split, against",
        "the published values. `free` excludes obstacle particles, `all` is the",
        "released code's convention; see `docs/REPLICATION.md`. Goop has no",
        "obstacle particles, so its two columns are identical and it is the",
        "cleanest comparison.",
        "",
        "| dataset | steps trained | one-step (free) | one-step (all) | paper | ratio |"
        " rollout (free) | rollout (all) | paper | ratio |",
        "| " + " --- |" * 10,
    ]
    for result in headline:
        name = result["dataset"]
        published_one = paper.one_step_mse(name)
        published_roll = paper.rollout_mse(name)
        lines.append(
            f"| {name} | {result['step']:,} "
            f"| {result['one_step_mse_free_particles']:.2e} "
            f"| {result['one_step_mse_all_particles']:.2e} "
            f"| {published_one:.2e} "
            f"| {ratio(result['one_step_mse_free_particles'], published_one)} "
            f"| {result['rollout_mse_free_particles']:.2e} "
            f"| {result['rollout_mse_all_particles']:.2e} "
            f"| {published_roll:.2e} "
            f"| {ratio(result['rollout_mse_free_particles'], published_roll)} |"
        )

    lines += [
        "",
        "The paper trains for up to 20M gradient steps. The step count above is",
        "what each run actually reached, and the ratio column is the honest cost",
        "of that gap; `figures/error_vs_time.png` shows where in a rollout the",
        "difference accumulates.",
        "",
        "## Figures",
        "",
        "| file | reproduces |",
        "| --- | --- |",
        "| `figures/table1.png` | Table 1 / C.4 |",
        "| `figures/error_vs_time.png` | Figure C.3 |",
        "| `figures/ablations.png` | Figure 4(a-j) |",
        "| `figures/rollout_*.png` | Figure 3, qualitative rollouts |",
        "",
    ]

    if ablations:
        lines += [
            "## Ablations",
            "",
            "All ablation runs share one reduced budget, so the comparison between",
            "bars is fair even though every bar sits above the published level.",
            "",
            "| axis | value | one-step MSE | rollout MSE | steps |",
            "| --- | --- | --- | --- | --- |",
        ]
        for result in sorted(
            ablations, key=lambda r: (r["ablation_axis"], str(r["ablation_value"]))
        ):
            lines.append(
                f"| {result['ablation_axis']} | {result['ablation_value']} "
                f"| {result['one_step_mse_free_particles']:.2e} "
                f"| {result['rollout_mse_free_particles']:.2e} "
                f"| {result['step']:,} |"
            )
        lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}: {len(headline)} headline, {len(ablations)} ablations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
